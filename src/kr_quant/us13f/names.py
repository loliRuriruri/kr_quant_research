def _norm(text: str) -> str:
    return " ".join(str(text or "").upper().replace(".", " ").replace(",", " ").split())


def korean_for_ticker(ticker: str | None) -> tuple[str, str] | None:
    if not ticker:
        return None
    hit = BY_TICKER.get(str(ticker).upper())
    return hit


def korean_for_issuer(issuer: str) -> tuple[str, str, str] | None:
    raw = _norm(issuer)
    if not raw:
        return None
    for needle, ticker, name_ko, note in ISSUER_HINTS:
        if needle in raw:
            return ticker, name_ko, note
    return None


def fallback_note(issuer: str, kind: str | None = None) -> str:
    label = (issuer or "").strip() or "이 종목"
    if kind and "ETF" in kind.upper():
        return f"{label} 미국 상장 ETF입니다."
    if "ETF" in _norm(issuer) or "ISHARES" in _norm(issuer) or "VANGUARD" in _norm(issuer) or "SPDR" in _norm(issuer):
        return f"{label} 미국 상장 ETF입니다."
    return f"{label} 미국 상장 증권입니다. 13F 보유 기준으로 봅니다."
